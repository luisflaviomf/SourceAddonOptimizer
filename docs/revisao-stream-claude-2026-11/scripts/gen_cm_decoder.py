"""Generates cm_decoder2.lua: the same decoder as cm_decoder.lua with every binary decision inlined (no
closures over the coder state: LuaJIT keeps range/code/pos in registers) and zero tiles skipped by tile."""
from pathlib import Path


def BIT(P, idx, out, ind):
    """inline adaptive decision on probability P[idx] -> local `out` (0/1)"""
    s = f"""
local _i = {idx}
local _p = {P}[_i]
local _b = floor(range * 0.000244140625) * _p
if code < _b then
    range = _b; {P}[_i] = _p + floor((4096 - _p) * 0.0625); {out} = 0
else
    code = code - _b; range = range - _b; {P}[_i] = _p - floor(_p * 0.0625); {out} = 1
end
if range < 16777216 then
    range = range * 256; code = code * 256 + byte(data, pos); pos = pos + 1
    if range < 16777216 then range = range * 256; code = code * 256 + byte(data, pos); pos = pos + 1 end
end"""
    return "\n".join(ind + line for line in s.strip("\n").split("\n"))


